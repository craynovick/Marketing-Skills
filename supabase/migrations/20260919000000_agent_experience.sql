create or replace function public.cookbook_create_task(p_slug text, p_version text, p_title text, p_key uuid)
returns uuid language plpgsql security invoker set search_path = public as $$
declare project uuid; task uuid;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text, 0));
  select id into task from cookbook_skills where user_id=auth.uid() and creation_key=p_key;
  if task is not null then return task; end if;
  select id into project from cookbook_projects where user_id=auth.uid() order by created_at limit 1;
  if project is null then insert into cookbook_projects(user_id) values(auth.uid()) returning id into project; end if;
  insert into cookbook_skills(user_id,project_id,file_name,title,skill_slug,skill_version,creation_key)
  values(auth.uid(),project,p_slug||'-'||substr(p_key::text,1,8)||'.md',p_title,p_slug,p_version,p_key) returning id into task;
  insert into cookbook_threads(user_id,skill_id) values(auth.uid(),task);
  return task;
end $$;

create or replace function public.cookbook_start_run(p_task uuid, p_run uuid, p_input text, p_attachments jsonb)
returns uuid language plpgsql security invoker set search_path = public as $$
declare thread uuid; existing cookbook_agent_runs; unlimited boolean;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text, 0));
  perform 1 from cookbook_skills where id=p_task and user_id=auth.uid() and archived_at is null for update;
  if not found then raise exception 'INVALID_TASK'; end if;
  select * into existing from cookbook_agent_runs where id=p_run and user_id=auth.uid();
  if existing.id is not null then raise exception 'DUPLICATE_RUN'; end if;
  update cookbook_agent_runs set status='interrupted',updated_at=now() where skill_id=p_task and user_id=auth.uid() and status='running' and updated_at<now()-interval '90 seconds';
  if exists(select 1 from cookbook_agent_runs where skill_id=p_task and user_id=auth.uid() and status='running') then raise exception 'RUN_ACTIVE'; end if;
  unlimited := coalesce(auth.jwt()->'app_metadata'->>'unlimited','false')='true' or coalesce(auth.jwt()->'app_metadata'->>'role','')='admin';
  if not unlimited and (select count(*) from cookbook_agent_runs where user_id=auth.uid() and created_at>now()-interval '1 hour') >= 30 then raise exception 'RATE_LIMITED'; end if;
  if length(p_input)>4000 or length(trim(p_input))=0 then raise exception 'INVALID_MESSAGE'; end if;
  select id into thread from cookbook_threads where skill_id=p_task and user_id=auth.uid();
  if thread is null then insert into cookbook_threads(user_id,skill_id) values(auth.uid(),p_task) returning id into thread; end if;
  insert into cookbook_agent_runs(id,user_id,skill_id,input,attachment_ids) values(p_run,auth.uid(),p_task,p_input,p_attachments);
  insert into cookbook_messages(user_id,thread_id,role,content,parts,message_key,metadata)
  values(auth.uid(),thread,'user',p_input,jsonb_build_array(jsonb_build_object('type','text','text',p_input)),p_run::text,jsonb_build_object('runId',p_run,'attachmentIds',p_attachments));
  return thread;
end $$;

create or replace function public.cookbook_save_document(p_task uuid,p_content text,p_expected integer,p_source text,p_operation text,p_run uuid default null,p_metadata jsonb default '{}')
returns public.cookbook_documents language plpgsql security invoker set search_path = public as $$
declare latest integer; result cookbook_documents;
begin
  perform 1 from cookbook_skills where id=p_task and user_id=auth.uid() for update;
  if not found then raise exception 'INVALID_TASK'; end if;
  select * into result from cookbook_documents where skill_id=p_task and user_id=auth.uid() and operation_key=p_operation;
  if result.id is not null then return result; end if;
  if p_run is not null then
    perform 1 from cookbook_agent_runs where id=p_run and skill_id=p_task and user_id=auth.uid() and status='running' for update;
    if not found then raise exception 'RUN_STOPPED'; end if;
  end if;
  select coalesce(max(version),0) into latest from cookbook_documents where skill_id=p_task and user_id=auth.uid();
  if p_expected is null or latest<>p_expected then raise exception 'STALE_VERSION'; end if;
  if length(p_content)>60000 or length(trim(p_content))=0 then raise exception 'INVALID_DOCUMENT'; end if;
  insert into cookbook_documents(user_id,skill_id,content,version,source,agent_version,status,run_id,operation_key,assumptions,unanswered_questions,evidence_references)
  values(auth.uid(),p_task,p_content,latest+1,p_source,'2026-09-19','review',p_run,p_operation,
    coalesce(p_metadata->'assumptions','[]'),coalesce(p_metadata->'questions','[]'),coalesce(p_metadata->'sources','[]')) returning * into result;
  update cookbook_skills set lifecycle='draft',updated_at=now() where id=p_task and user_id=auth.uid();
  return result;
end $$;

create or replace function public.cookbook_accept_document(p_task uuid,p_version integer)
returns uuid language plpgsql security invoker set search_path = public as $$
declare doc cookbook_documents;
begin
  perform 1 from cookbook_skills where id=p_task and user_id=auth.uid() for update;
  if not found then raise exception 'INVALID_TASK'; end if;
  select * into doc from cookbook_documents where skill_id=p_task and user_id=auth.uid() order by version desc limit 1;
  if doc.id is null or doc.version<>p_version then raise exception 'STALE_VERSION'; end if;
  update cookbook_skills set lifecycle='accepted',accepted_version_id=doc.id,updated_at=now() where id=p_task;
  insert into cookbook_acceptance_events(user_id,skill_id,document_id) values(auth.uid(),p_task,doc.id);
  return doc.id;
end $$;

